/**
 * Generates public/sitemap.xml from the shared route map in src/lib/siteRoutes.ts.
 * Run with: npm run generate:sitemap
 */
import fs from 'node:fs';
import path from 'node:path';
import { SITE_ORIGIN, SITE_SECTIONS, absoluteUrlForPath } from '../src/lib/siteRoutes';

export function buildSitemapXml(lastmod: string): string {
  const urls = SITE_SECTIONS.map((section) => {
    const loc = absoluteUrlForPath(section.path);
    return `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </url>`;
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/generate-sitemap.ts from src/lib/siteRoutes.ts. Do not edit by hand. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls,
    '</urlset>',
    '',
  ].join('\n');
}

export function buildRobotsTxt(): string {
  return [
    '# MUQABIL robots policy',
    'User-agent: *',
    'Allow: /',
    'Disallow: /admin',
    'Disallow: /api/',
    '',
    `Sitemap: ${SITE_ORIGIN}/sitemap.xml`,
    '',
  ].join('\n');
}

function isoDateToday(): string {
  return new Date().toISOString().slice(0, 10);
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('generate-sitemap.ts')) {
  const publicDir = path.resolve(process.cwd(), 'public');
  fs.writeFileSync(path.join(publicDir, 'sitemap.xml'), buildSitemapXml(isoDateToday()), 'utf-8');
  fs.writeFileSync(path.join(publicDir, 'robots.txt'), buildRobotsTxt(), 'utf-8');
  console.log(`Wrote ${SITE_SECTIONS.length} URLs to public/sitemap.xml and public/robots.txt`);
}
